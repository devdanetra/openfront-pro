// Generates src/page-themes.css: for each theme in src/themes.js that has a
// `site` recipe, a value for EVERY colour
// variable OpenFront's stylesheets use (tools/used-colors.json, captured from
// the live site - 108 variables in 26 families).
//
//   node tools/gen-page-themes.mjs
//
// Why generated: the first version hand-picked ~20 variables, so anything else -
// above all the darker shades that buttons switch to on :hover - fell back to
// the original palette and the theme visibly "dropped" under the cursor. Covering
// every variable by family and shade removes that whole class of bug, and a
// re-run after a site update picks up any new ones.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), ".."); // survives spaces in the path
const used = JSON.parse(fs.readFileSync(path.join(ROOT, "tools/used-colors.json"), "utf8")).map(([n]) => n);

// Tailwind v4's own lightness / chroma ramps (oklch), for a colour family and
// for a neutral one, so generated shades sit where the site's CSS expects.
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const COLOR_L = [0.97, 0.932, 0.882, 0.809, 0.707, 0.623, 0.546, 0.488, 0.424, 0.379, 0.282];
const COLOR_C = [0.014, 0.032, 0.059, 0.105, 0.165, 0.214, 0.245, 0.243, 0.199, 0.146, 0.091];
const NEUTRAL_L = [0.985, 0.967, 0.928, 0.872, 0.707, 0.551, 0.446, 0.373, 0.278, 0.21, 0.13];

const ROLE = {
  blue: "primary", sky: "primary", cyan: "primary", indigo: "primary",
  green: "success", emerald: "success", teal: "success",
  red: "danger", rose: "danger",
  amber: "warning", yellow: "warning", orange: "warning",
  purple: "accent", violet: "accent", fuchsia: "accent",
  gray: "surface", slate: "surface", zinc: "surface", neutral: "surface",
};

// The theme list is src/themes.js (one catalogue for the extension's own look
// and for the site): `site` = hue per role, surface tint, chroma multiplier,
// light or dark. A theme without `site` (classic) leaves OpenFront alone.
await import(pathToFileURL(path.join(ROOT, "src/themes.js")).href);
const CATALOGUE = globalThis.OFR_THEMES;
const THEMES = Object.fromEntries(
  Object.entries(CATALOGUE).filter(([, t]) => t.site).map(([id, t]) => [id, t.site]),
);

const f = (n) => Number(n.toFixed(3));
const oklch = (l, c, h) => `oklch(${f(l)} ${f(c)} ${f(h)})`;

function shadeIndex(shade) {
  const i = SHADES.indexOf(Number(shade));
  return i === -1 ? 5 : i;
}

function colorFor(name, t) {
  // named one-offs first
  if (name === "white") return t.light ? oklch(0.27, 0.03, t.surfaceHue) : "#ffffff";
  if (name === "black") return t.light ? oklch(0.99, 0.005, t.surfaceHue) : "#000000";
  if (name === "malibu-blue") return oklch(t.light ? 0.55 : 0.66, 0.18 * t.boost, t.primary);
  if (name === "aquarius") return oklch(t.light ? 0.6 : 0.74, 0.14 * t.boost, t.primary + 25);
  if (name === "cyber-yellow") return oklch(t.light ? 0.7 : 0.86, 0.17 * t.boost, t.warning);
  if (name === "surface") return t.light ? oklch(0.96, t.surfaceC, t.surfaceHue) : oklch(t.contrast ? 0 : 0.2, t.surfaceC, t.surfaceHue);
  if (name === "deep-navy") return t.light ? oklch(0.93, t.surfaceC, t.surfaceHue) : oklch(0.15, t.surfaceC, t.surfaceHue);

  const m = name.match(/^([a-z]+)-(\d+)$/);
  if (!m) return null;
  const [, family, shade] = m;
  const role = ROLE[family];
  if (!role) return null;
  let i = shadeIndex(shade);

  if (role === "surface") {
    // light theme: flip the ramp so "gray-900" (a panel background) is pale and
    // "gray-100" (text on it) is dark
    if (t.light) i = SHADES.length - 1 - i;
    let l = NEUTRAL_L[i];
    if (t.contrast) l = l > 0.5 ? Math.min(1, l + 0.05) : Math.max(0, l - 0.13);
    return oklch(l, t.surfaceC * (l > 0.5 ? 0.6 : 1), t.surfaceHue);
  }

  let l = COLOR_L[i];
  if (t.light) l = Math.max(0.3, l - 0.1); // deeper, to read on pale surfaces
  return oklch(l, COLOR_C[i] * t.boost, t[role]);
}

let css = `/* GENERATED by tools/gen-page-themes.mjs - do not edit by hand.
   One block per page theme, overriding every colour variable OpenFront's CSS
   uses (${used.length} of them), so base, hover, focus and active states all stay
   inside the theme. Applied as <html data-ofr-page-theme="...">. */\n`;

for (const [id, t] of Object.entries(THEMES)) {
  const lines = [];
  for (const name of used) {
    const value = colorFor(name, t);
    if (value) lines.push(`  --color-${name}: ${value};`);
  }
  css += `\nhtml[data-ofr-page-theme="${id}"] {\n${lines.join("\n")}\n}\n`;
  console.log(id.padEnd(9), lines.length, "of", used.length, "variables");
}

fs.writeFileSync(path.join(ROOT, "src/page-themes.css"), css);
console.log("wrote src/page-themes.css", (css.length / 1024).toFixed(1), "KB");

// ---- consistency: one id, three places ------------------------------------------
// Every theme but classic needs a token block in content.css; every token block
// needs a catalogue entry. A mismatch is a half-applied theme, so fail loudly.
const tokenCss = fs.readFileSync(path.join(ROOT, "src/content.css"), "utf8");
const tokenIds = new Set([...tokenCss.matchAll(/html\[data-ofr-theme="([a-z0-9-]+)"\]\s*\{/g)].map((m) => m[1]));
const problems = [];
for (const id of Object.keys(CATALOGUE)) {
  if (id !== "classic" && !tokenIds.has(id)) problems.push(`themes.js has "${id}" but content.css has no html[data-ofr-theme="${id}"] block`);
  if (id !== "classic" && !CATALOGUE[id].site) problems.push(`theme "${id}" has no site recipe`);
}
for (const id of tokenIds) {
  if (!CATALOGUE[id]) problems.push(`content.css styles "${id}" but themes.js does not list it`);
}
if (problems.length) {
  console.error("THEME MISMATCH:\n  " + problems.join("\n  "));
  process.exit(1);
}
console.log("themes consistent:", Object.keys(CATALOGUE).join(", "));
